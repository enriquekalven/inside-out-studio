const VALID_CODES = new Set(LANGUAGES.map((l) => l.code));

function detectInitialLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const urlLang = params.get('lang');
    if (urlLang && VALID_CODES.has(urlLang)) return urlLang;
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && VALID_CODES.has(saved)) return saved;
  } catch {
    // ignore storage errors
  }
  return 'en';
}

let currentLang = detectInitialLang();
const listeners = new Set();

export function getLang() {
  return currentLang;
}

export function getLangMeta(code = currentLang) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

export function setLang(nextCode) {
  if (!VALID_CODES.has(nextCode)) nextCode = 'en';
  currentLang = nextCode;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, currentLang);
  } catch {
    // ignore
  }
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = currentLang;
  }
  for (const fn of listeners) {
    try {
      fn(currentLang);
    } catch {
      // ignore listener errors
    }
  }
  return currentLang;
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

